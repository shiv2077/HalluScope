"""Render itemtriage reports from results JSON only. Never parses markdown."""

from __future__ import annotations

from . import paths

H1_OUT = paths.REPORTS / "itemtriage_h1.md"


def pct(d, k=1):
    if d is None:
        return "n/a"
    return f"{100 * d['est']:.{k}f}% [{100 * d['lo']:.{k}f}, {100 * d['hi']:.{k}f}]"


def num(d, k=3):
    if d is None:
        return "n/a"
    return f"{d['est']:.{k}f} [{d['lo']:.{k}f}, {d['hi']:.{k}f}]"


def pp(d, k=1):
    """A difference of proportions, in percentage points, with the share of resamples at or below zero."""
    if d is None:
        return "n/a"
    out = f"{100 * d['est']:+.{k}f} [{100 * d['lo']:+.{k}f}, {100 * d['hi']:+.{k}f}] points"
    if "share_resamples_at_or_below_zero" in d:
        out += f" ({100 * d['share_resamples_at_or_below_zero']:.1f}% of resamples at or below zero)"
    return out


def dec(d, k):
    return "n/a" if d is None else f"{d['est']:.{k}f} [{d['lo']:.{k}f}, {d['hi']:.{k}f}]"


def _metric_table(block: dict, names: list[str], budgets: list) -> list[str]:
    L = ["| scorer | " + " | ".join(f"precision at {int(100 * b)}%" for b in budgets) + " | recall at 10% | lift at 10% | AP | AUROC |",
         "|---|" + "---|" * (len(budgets) + 4)]
    for k in names:
        s = block["scorers"][k]
        L.append(f"| `{k}` | " + " | ".join(pct(s[f"precision_{b}"]) for b in budgets) +
                 f" | {pct(s['recall_0.1'])} | {num(s['lift_0.1'], 2)} | {num(s['ap'])} | {num(s['auroc'])} |")
    s0 = block["scorers"][names[0]]
    L.append("| best possible | " + " | ".join(f"{100 * s0['ceiling'][str(b)]:.1f}%" for b in budgets) + " | | | 1.000 | 1.000 |")
    return L


def h1_text(o: dict) -> str:
    irt = o["irt_selection"]["chosen"]
    names = ["conf_w", "conf", "disagree", irt, "ptrue_key", "lr", "length", "dup_options"]
    names = [n for n in names if n in o["classes"]["primary"]["scorers"]]
    budgets = o["budgets"]
    P, S = o["classes"]["primary"], o["classes"]["secondary"]
    h = o["h1a"]
    c1, c2 = h["contrasts"]["conf_w-disagree"], h["contrasts"][f"conf_w-{irt}"]
    L = ["# itemtriage: H1 results", "",
         f"Generated by `python3 -m itemtriage.cli evaluate` from `results/itemtriage/evaluation.json`. Preregistration commit "
         f"`{o['prereg']['prereg_commit'][:12]}`; first unblinded under `{o['prereg']['unblinded_under'][:12]}`"
         + (" (deviation: the preregistration changed after unblinding)." if o["prereg"]["deviation"] else "."), "",
         "Brackets are 95 percent intervals: 2000-resample bootstrap with seed 42, paired for differences, Wilson for "
         "rates. Budget metrics resolve ties in expectation, never by row order.", "",
         *[x for a in o.get("amendments", []) for x in (f"**{a}**", "")],
         "## Verdicts", "",
         f"**H1a {'holds' if h['holds'] else 'does not hold'}.** At a 10% review budget on the primary class, `conf_w` minus "
         f"`disagree` is {pp(c1)} and `conf_w` minus `{irt}` is {pp(c2)}. The rule needs both intervals entirely above zero.", "",
         f"**H1b is not computable.** {o['h1b']['reason']}.", "",
         "## Panel", "",
         "| model | ability θ | weight in `conf_w` |", "|---|---:|---:|"]
    for m in o["panel"]:
        L.append(f"| `{m}` | {o['theta'][m]:.3f} | {o['weights'][m]:.3f} |")
    L += ["", f"IRT variant carried forward: `{irt}`, chosen on validation average precision "
          f"({', '.join(f'`{k}` {v:.3f}' for k, v in o['irt_selection']['validation_ap'].items())}). "
          f"`lr` used C = {o['lr']['C']}, fit on {o['lr']['n_fit']} calibration items.", "",
          f"## Primary class: ground-truth errors (test, {P['n']} known items, {P['positives']} positives, base rate {pct(P['base_rate'])})", "",
          f"{o['unknown_excluded_test']} test items marked `expert` are excluded.", ""]
    L += _metric_table(P, names, budgets)
    L += ["", f"## Secondary class: any flaw (test, {S['n']} known items, {S['positives']} positives, base rate {pct(S['base_rate'])})", ""]
    L += _metric_table(S, names, budgets)
    V = o["virology_excluded"]
    L += ["", f"## Exploratory: virology excluded (primary class, {V['n']} items, {V['positives']} positives)", ""]
    L += _metric_table(V, names, budgets)
    vc = V["paired_precision_diff"]
    L += ["", "Paired differences at 10%: " + "; ".join(f"`{k}` {pp(v)}" for k, v in vc.items()) + ".", "",
          "## Cost per error found (primary class)", "",
          "API dollars come from logged tokens and `config/pricing.json`. Local models cost $0. Reviewer minutes assume "
          f"{o['cost']['review_minutes_per_item_assumed']:g} minutes per reviewed item, which is an assumption, not a measurement.", "",
          "| scorer | API $ per item | errors found at 10% | API $ per error at 10% | assumed reviewer minutes per error at 10% |",
          "|---|---:|---|---|---|"]
    for k in names:
        c = o["cost"]["per_scorer"][k]
        b = c["budgets"]["0.1"]
        ef = b["errors_found"]
        usd, mins = b["usd_per_error"], b["review_minutes_per_error_assumed"]
        L.append(f"| `{k}` | {c['api_usd_per_item']:.5f} | {dec(ef, 1)} | {dec(usd, 3)} | {dec(mins, 1)} |")
    L += ["", "## Exploratory: agreement with the key, flawed versus ok calibration items", "",
          "A model that agrees with wrong keys as often as with right ones may have memorized them.", "",
          "| model | agrees with key on flawed items | agrees with key on ok items |", "|---|---|---|"]
    for m, r in o["memorization_exploratory"].items():
        L.append(f"| `{m}` | {pct(r['flawed'])} | {pct(r['ok'])} |")
    L.append("")
    return "\n".join(L)


def write_h1(o: dict) -> None:
    paths.REPORTS.mkdir(parents=True, exist_ok=True)
    H1_OUT.write_text(h1_text(o))


FINAL_OUT = paths.REPORTS / "itemtriage_report.md"


def _load(p):
    import json

    return json.loads(p.read_text()) if p.exists() else None


def explore_text(X: dict) -> list[str]:
    names = X["scorers"]
    L = ["## Exploratory, post-unblinding: bad items or bad subjects?", "",
         f"{X['label']} Splits are by subject, so a high score could only mean \"this item is in a bad subject\". "
         "`subject_mean` gives every item the mean `conf_w` of its subject. It has no secondary key, so ties inside a "
         "subject resolve in expectation. `within_subject` is `conf_w` minus `subject_mean`. Both are label-free. "
         "Primary class, test fold.", ""]
    for key, title in (("all", "All test items"), ("virology_excluded", "Virology excluded")):
        b = X[key]
        L += [f"**{title}** ({b['n']} items, {b['positives']} positives).", ""]
        L += _metric_table(b, names, [0.05, 0.1, 0.2])
        L += ["", "Paired differences at 10%: " + ", ".join(f"`{k}` {pp(v)}" for k, v in b["paired_precision_diff"].items()) + ".", ""]
    ps = X["per_subject"]
    pos = [r for r in ps if r["positives"] > 0]
    zero = [r for r in ps if r["positives"] == 0]
    L += [f"**Per subject, at a 10% budget.** Recall with a Wilson interval. Flagged is the expected number of the subject's "
          f"items in the flagged slice. {len(zero)} of {len(ps)} test subjects have no positives.", "",
          "| subject | items | positives | " + " | ".join(f"`{s}` recall (flagged)" for s in names) + " |",
          "|---|---:|---:|" + "---|" * len(names)]
    for r in pos:
        L.append(f"| {r['subject']} | {r['items']} | {r['positives']} | " +
                 " | ".join(f"{pct(r['recall'][s], 0)} ({r['flagged'][s]:.0f})" for s in names) + " |")
    L.append(f"| {len(zero)} subjects with no positives | {sum(r['items'] for r in zero)} | 0 | " +
             " | ".join(f"({sum(r['flagged'][s] for r in zero):.0f})" for s in names) + " |")
    L += ["", "**Memorization, test fold.** Share of items where each model's answer equals the key, with Wilson intervals. "
          "Chance is 25% on four options.", "", "| model | flawed items | ok items |", "|---|---|---|"]
    for m, v in X["memorization_test"].items():
        L.append(f"| `{m}` | {pct(v['flawed'])} | {pct(v['ok'])} |")
    return L + [""]


def final_text() -> str:
    from . import calibrate, evaluate, explore, human

    E, H2, C = _load(evaluate.EVAL_OUT), _load(evaluate.H2_OUT), _load(calibrate.CAL_OUT)
    HU = human.agreement()
    L = ["# itemtriage report", "",
         "Ranks multiple-choice items (question plus answer key) for expert review under a fixed budget, using a small "
         "model panel's answers and confidence. Ground truth is MMLU-Redux 2.0 expert annotation. Generated by "
         "`python3 -m itemtriage.cli report` from `results/itemtriage/*.json`; regenerate on CPU without API calls.", "",
         *[x for a in (E or {}).get("amendments", []) for x in (f"**{a}**", "")],
         "## Verdicts", ""]
    if E is None:
        L += ["H1 has not been evaluated yet: the panel pass is incomplete.", ""]
    else:
        irt = E["irt_selection"]["chosen"]
        c = E["h1a"]["contrasts"]
        L += [f"- **H1a {'holds' if E['h1a']['holds'] else 'does not hold'}.** Precision at a 10% budget, primary class: "
              f"`conf_w` minus `disagree` {pp(c['conf_w-disagree'])}; `conf_w` minus `{irt}` {pp(c[f'conf_w-{irt}'])}.",
              f"- **H1b is not computable.** {E['h1b']['reason']}."]
    if H2 is None:
        L.append("- **H2 not run.** The hidden-state capture has not completed.")
    else:
        d = H2["result"]["paired_precision_diff"]["lr_probe-lr"]
        L.append(f"- **H2 {'holds' if H2['h2']['holds'] else 'does not hold'}.** `lr` plus the probe minus `lr`, precision at "
                 f"10%: {pp(d)}. {'The tier stays.' if H2['h2']['holds'] else 'The tier is dropped.'}")
    if C is None:
        L.append("- **H3 not run.**")
    else:
        fc = C["fixed_cutoffs"]["conf_w"]
        drift = "; ".join(f"{int(100 * float(b))}% cutoff flags {pct(v['test_flag_rate'])} of test" for b, v in fc.items())
        q = [a for a, r in C["risk_deviation"]["conf_w"].items() if r.get("threshold") is not None]
        L.append(f"- **H3.** Fixed `conf_w` cutoffs from calibration: {drift}. The budget policy flags exactly the budget. "
                 "The preregistered risk lane cannot qualify by construction. Under the declared fix, `conf_w` qualifies at alpha "
                 + (", ".join(q) if q else "none") + ", where the base rate is already below alpha; see H3 below.")
    L.append("")
    if E is not None:
        body = h1_text(E)
        L += [body[body.index("## Panel"):], ""]
    X = _load(explore.OUT)
    if X is not None:
        L += explore_text(X)
    if H2 is not None:
        r = H2["result"]
        L += ["## H2: hidden-state tier", "",
              f"Model `{H2['model']}`, keyed letter appended as the assistant turn. Features: middle-third mean and depth "
              f"0.5 and 0.75 layers at the key token, middle-third mean at the last prompt token. PCA to "
              f"{H2['probe']['pca_dim']}, L2 logistic regression, C = {H2['probe']['C']} chosen on validation.", "",
              f"Clarification beyond the preregistration: {H2['clarification']}.", ""]
        L += _metric_table(r, ["lr_probe", "lr", "probe", "conf_w"], [0.05, 0.1, 0.2])
        L += ["", "Paired differences at 10%: " + "; ".join(f"`{k}` {pp(v)}" for k, v in r["paired_precision_diff"].items()) + ".", ""]
    if C is not None:
        L += ["## H3: cutoff transfer and the risk lane", "",
              f"Cutoffs fit on {C['n_calibration']} calibration items ({C['calibration_positives']} primary positives), "
              f"applied to {C['n_test']} test items. Scores hash `{C['scores_hash']}`, labels hash `{C['labels_hash']}`.", "",
              "| scorer | budget | calibration cutoff | test flag rate at that cutoff | budget policy flag rate |",
              "|---|---:|---:|---|---:|"]
        for k, rows in C["fixed_cutoffs"].items():
            for b, v in rows.items():
                L.append(f"| `{k}` | {float(b):.2f} | {v['cutoff']:.4f} | {pct(v['test_flag_rate'])} | {100 * v['budget_policy_flag_rate']:.1f}% |")
        base = C["calibration_positives"] / C["n_calibration"]
        L += ["", "Learn-Then-Test, delta 0.10, risk = primary flaw rate among accepted items. The preregistered implementation "
              "(`routing.calibrate.calibrate_risk`) starts its fixed sequence at the single lowest score, where one accepted item gives "
              "a Hoeffding bound above 1, so it fails its first test and can never return a threshold. Its result is shown first. "
              "The second table is a declared post-unblinding deviation that starts the same fixed sequence at 10% coverage.", "",
              "| scorer | alpha | preregistered result | deviation: threshold | calibration coverage | test coverage | test risk |",
              "|---|---:|---|---|---|---|---|"]
        for k, rr in C["risk"].items():
            for a, r in rr.items():
                dv = C["risk_deviation"][k][a]
                pre = "none qualifies" if r.get("threshold") is None else f"{r['threshold']:.4f}"
                if dv.get("threshold") is None:
                    L.append(f"| `{k}` | {a} | {pre} | none qualifies | | | |")
                else:
                    L.append(f"| `{k}` | {a} | {pre} | {dv['threshold']:.4f} | {100 * dv['coverage_cal']:.1f}% | "
                             f"{pct(dv['test_coverage'])} | {pct(dv['test_risk'])} |")
        L += ["", f"The calibration base rate is {100 * base:.2f}%. Wherever alpha is above it, accepting nearly every item "
              "already satisfies the bound, so qualification at those alphas says nothing about ranking. Only alpha 0.05 is informative here."]
        rq = C["required_n"]["conf_w"]
        L += ["", "Required calibration size for `conf_w` (n_acc = ln(1/delta) / (2 (alpha - risk_hat)^2) over coverage); "
              "`none` means the empirical risk at that coverage already exceeds alpha:", "",
              "| coverage | risk at that coverage | alpha 0.05 | alpha 0.10 | alpha 0.20 |", "|---:|---:|---:|---:|---:|"]
        for cov, v in rq.items():
            L.append(f"| {cov} | {100 * v['risk_hat_at_coverage']:.2f}% | " + " | ".join(str(v["required_n"][a]) for a in ("0.05", "0.1", "0.2")) + " |")
        L.append("")
    L += ["## Non-expert spot check", ""]
    if HU is None:
        L += ["Not run yet. `python3 -m itemtriage.cli label --annotator <name>` shows 150 items blind.", ""]
    else:
        for a, r in HU.items():
            L += [f"Annotator `{a}`, a non-expert check on judgeable subjects only.", "",
                  "| pool | labelled | unsure | human flawed rate | dataset flawed rate |", "|---|---:|---:|---|---|"]
            for pool in ("top", "random"):
                x = r[pool]
                L.append(f"| {pool} | {x['labelled']} | {x['unsure']} | {pct(x['human_flawed_rate'])} | {pct(x['dataset_flawed_rate'])} |")
            L += ["", f"Agreement with the dataset label {pct(r['agreement_with_dataset'])}, kappa {num(r['kappa'])}.", ""]
    L += ["## Limitations", "",
          "- One benchmark, short multiple-choice items, a 3.5% base rate. Precision at 10% cannot exceed about a third.",
          "- Direct letter answers without reasoning; reasoning-prompted panels may behave differently.",
          "- Two OpenAI and two Qwen models share lineage, so the effective panel is smaller than its size.",
          "- MMLU is in pretraining data; models can reproduce memorized wrong keys.",
          "- `expert` items are excluded, not resolved.", "",
          "## Reproduce", "", "```bash",
          "python3 -m itemtriage.cli collect && python3 -m itemtriage.cli score && python3 -m itemtriage.cli evaluate",
          "python3 -m itemtriage.cli calibrate && python3 -m itemtriage.cli h2 && python3 -m itemtriage.cli report",
          "```", "",
          "Everything above `h2` regenerates from the committed `data/itemtriage/panel_responses.parquet`. `h2` also needs the "
          "hidden-state cache, which is too large to commit: rebuild it with `.venv/bin/python -m itemtriage.cli hidden-capture` "
          "(about 25 minutes on the GPU).", ""]
    return "\n".join(L)


def write_final() -> None:
    paths.REPORTS.mkdir(parents=True, exist_ok=True)
    FINAL_OUT.write_text(final_text())


README = paths.ROOT / "README.md"
START, END = "<!-- itemtriage:start -->", "<!-- itemtriage:end -->"


def readme_block() -> str:
    from . import calibrate, evaluate, explore

    E, H2, C, X = _load(evaluate.EVAL_OUT), _load(evaluate.H2_OUT), _load(calibrate.CAL_OUT), _load(explore.OUT)
    L = [START, "## Results", "",
         "Generated by `python3 -m itemtriage.cli report` from `results/itemtriage/*.json`. Ground truth is MMLU-Redux 2.0 "
         "expert annotation. The preregistration is [`docs/PREREG.md`](docs/PREREG.md) and the full report is "
         "[`reports/itemtriage_report.md`](reports/itemtriage_report.md). Brackets are 95% intervals.", ""]
    if E is None or X is None:
        L += ["Results are pending.", END]
        return "\n".join(L)
    P = E["classes"]["primary"]
    cw = P["scorers"]["conf_w"]
    c = E["h1a"]["contrasts"]
    A, V = X["all"], X["virology_excluded"]
    vir = next(r for r in X["per_subject"] if r["subject"] == "virology")
    L += [f"The panel is {len(E['panel'])} local models answering zero-shot by letter: "
          + ", ".join(f"`{m}`" for m in E["panel"]) + f". On {P['n']} test items with {P['positives']} "
          f"expert-labelled errors (base rate {pct(P['base_rate'])}), reviewing the top 10% ranked by the IRT-weighted "
          f"confidence score `conf_w` finds errors at precision {pct(cw['precision_0.1'])}, against a best possible "
          f"{100 * cw['ceiling']['0.1']:.1f}%, with recall {pct(cw['recall_0.1'])}.", "",
          f"Most of that comes from one subject. Virology holds {vir['positives']} of the {P['positives']} errors in "
          f"{vir['items']} items. With virology excluded, `conf_w` is no better than the item-length control.", "",
          "| scorer | what it uses | precision at 10%, all test items | precision at 10%, virology excluded |",
          "|---|---|---|---|"]
    what = {"conf_w": "panel confidence, IRT-weighted", "disagree": "share of the panel that misses the key",
            "subject_mean": "mean `conf_w` of the item's subject", "within_subject": "`conf_w` minus `subject_mean`",
            "length": "characters in question and options (control)"}
    for k in ("conf_w", "disagree", "subject_mean", "within_subject", "length"):
        L.append(f"| `{k}` | {what[k]} | {pct(A['scorers'][k]['precision_0.1'])} | {pct(V['scorers'][k]['precision_0.1'])} |")
    mem = X["memorization_test"]
    lo, hi = min(v["flawed"]["est"] for v in mem.values()), max(v["flawed"]["est"] for v in mem.values())
    lo2, hi2 = min(v["ok"]["est"] for v in mem.values()), max(v["ok"]["est"] for v in mem.values())
    zero = [r for r in X["per_subject"] if r["positives"] == 0]
    L += ["", "Findings:", "",
          f"- **Confidence adds little over plain disagreement (H1a does not hold).** `conf_w` minus `disagree`, precision "
          f"at 10%: {pp(c['conf_w-disagree'])}."]
    if H2 is not None:
        d = H2["result"]["paired_precision_diff"]["lr_probe-lr"]
        L.append(f"- **Hidden states hurt (H2 does not hold).** Adding a hidden-state probe to the supervised `lr` tier "
                 f"changes precision at 10% by {pp(d)}.")
    L += [f"- **Exploratory, post-unblinding: the signal is not a subject effect.** `subject_mean` ranks hard subjects, not flawed ones. At 10% it puts "
          f"{sum(r['flagged']['subject_mean'] for r in zero):.0f} of its flags in the {len(zero)} test subjects with no "
          f"errors. `conf_w` beats it by {pp(A['paired_precision_diff']['conf_w-subject_mean'])}.",
          f"- **Exploratory, post-unblinding: nor is it a clean item effect.** The within-subject residual is no better "
          f"than length: {pp(A['paired_precision_diff']['within_subject-length'])}.",
          f"- **Exploratory, post-unblinding: no sign of memorised wrong keys at this model size.** On flawed test items the models pick the key "
          f"{100 * lo:.1f}% to {100 * hi:.1f}% of the time, near the 25% chance rate, against {100 * lo2:.1f}% to "
          f"{100 * hi2:.1f}% on sound items."]
    if C is not None:
        fc = C["fixed_cutoffs"]["conf_w"]["0.1"]
        L.append(f"- **Fixed cutoffs drift (H3).** A `conf_w` cutoff fixed at the calibration 10% quantile flags "
                 f"{pct(fc['test_flag_rate'])} of test items. The budget policy flags exactly 10%.")
    L += [""] + [f"{a}" for a in E.get("amendments", [])] + ["", END]
    return "\n".join(L)


def update_readme() -> None:
    text = README.read_text()
    block = readme_block()
    if START in text and END in text:
        a, b = text.index(START), text.index(END) + len(END)
        text = text[:a] + block + text[b:]
    else:
        anchor = "## Why routing and not detection"
        i = text.index(anchor)
        text = text[:i] + block + "\n\n" + text[i:]
    README.write_text(text)
