"""Phase 1 findings: dataset facts, split class counts, power and ceiling notes, panel and cost projection.

Writes results/itemtriage/phase1.json and reports/phase1_findings.md. Every number comes from the data.
"""

from __future__ import annotations

import json
import math

import pandas as pd

from routing import stats

from . import costs, paths, prompts, splits
from . import labels as labels_mod

BUDGETS = (0.05, 0.10, 0.20)
PANEL = [
    {"model": "gpt-4o", "family": "OpenAI", "access": "api", "loading": "API, logprobs top 20"},
    {"model": "gpt-4o-mini", "family": "OpenAI", "access": "api", "loading": "API, logprobs top 20"},
    {"model": "Qwen/Qwen2.5-3B-Instruct", "family": "Qwen", "access": "local", "loading": "NF4", "params_b": 3.09},
    {"model": "Qwen/Qwen2.5-1.5B-Instruct", "family": "Qwen", "access": "local", "loading": "fp16", "params_b": 1.54},
    {"model": "microsoft/Phi-3.5-mini-instruct", "family": "Microsoft", "access": "local", "loading": "NF4", "params_b": 3.82},
    {"model": "HuggingFaceTB/SmolLM2-1.7B-Instruct", "family": "Hugging Face", "access": "local", "loading": "fp16", "params_b": 1.71},
    {"model": "ibm-granite/granite-3.1-2b-instruct", "family": "IBM", "access": "local", "loading": "NF4", "params_b": 2.53},
]
RESERVE = {"model": "allenai/OLMo-2-0425-1B-Instruct", "family": "AI2", "access": "local", "loading": "fp16", "params_b": 1.48}


def api_plan(items: list[dict]) -> list[dict]:
    mc = sum(len(prompts.mc_prompt(i)[0]) for i in items) / len(items) / 4 + costs.CHAT_OVERHEAD_TOKENS
    pt = sum(len(prompts.ptrue_prompt(i)) for i in items) / len(items) / 4 + costs.CHAT_OVERHEAD_TOKENS
    plan = []
    for m in ("gpt-4o", "gpt-4o-mini"):
        for purpose, est in (("mc", mc), ("ptrue", pt)):
            plan.append({"model": m, "purpose": f"{purpose}:pilot", "n_calls": 300, "est_input_tokens": est, "est_output_tokens": 1})
            plan.append({"model": m, "purpose": f"{purpose}:full", "n_calls": len(items) - 300, "est_input_tokens": est,
                         "est_output_tokens": 1})
    return plan


def run() -> dict:
    items = pd.read_parquet(paths.ITEMS)
    lab = labels_mod.load(caller="itemtriage.findings")
    sp = splits.load()
    fold = splits.fold_of(sp)
    m = items[["item_id", "subject"]].merge(lab, on="item_id")
    m["fold"] = m["item_id"].map(fold)
    folds = {}
    for f, g in m.groupby("fold"):
        known = g.dropna(subset=["flaw_primary"])
        n, pos, anyf = len(known), int(known["flaw_primary"].sum()), int(known["flaw_any"].sum())
        b = {}
        for bud in BUDGETS:
            k = math.ceil(bud * n)
            wl = stats.wilson(round(0.3 * k), k)
            b[str(bud)] = {"flagged": k, "precision_ceiling": min(pos, k) / k, "random_precision": pos / n,
                           "wilson_halfwidth_at_p0.3": (wl["hi"] - wl["lo"]) / 2}
        folds[f] = {"subjects": int(g["subject"].nunique()), "items": len(g), "known": n, "unknown": int(g["flaw_primary"].isna().sum()),
                    "primary": pos, "any_flaw": anyf, "primary_rate": stats.wilson(pos, n), "budgets": b}
    out = {"dataset": {"items": len(items), "subjects": int(items["subject"].nunique()),
                       "error_type_counts": lab["error_type_raw"].value_counts().to_dict(),
                       "duplicate_items": int(items["text_hash"].duplicated(keep=False).sum())},
           "split_sha256": sp["sha256"], "folds": folds, "test_has_100_primary": folds["test"]["primary"] >= 100,
           "panel": PANEL, "reserve": RESERVE, "cost": costs.project(api_plan(items.to_dict("records")))}
    paths.RESULTS.mkdir(parents=True, exist_ok=True)
    (paths.RESULTS / "phase1.json").write_text(json.dumps(out, indent=1, sort_keys=True, default=float))
    (paths.REPORTS / "phase1_findings.md").write_text(render(out))
    return out


def _pct(d):
    return f"{100 * d['est']:.2f}% [{100 * d['lo']:.2f}, {100 * d['hi']:.2f}]"


def render(o: dict) -> str:
    d, F, c = o["dataset"], o["folds"], o["cost"]
    L = ["# itemtriage Phase 1 findings", "",
         "Generated by `python3 -m itemtriage.cli findings` from `data/itemtriage/`. Proportions carry Wilson intervals.", "",
         "## Data", "",
         f"MMLU-Redux 2.0 (`edinburgh-dawg/mmlu-redux-2.0`, CC-BY-4.0): {d['items']} items, {d['subjects']} subjects of 100, "
         "4 options each. Columns: question, choices, answer, error_type, source, correct_answer, potential_reason. "
         "Only question, choices and answer enter `items.parquet`. The rest go to `labels.parquet`.", "",
         "| error_type | items | class |", "|---|---:|---|"]
    cls = {**{k: "primary and secondary" for k in paths.PRIMARY}, **{k: "secondary only" for k in paths.SECONDARY_ONLY},
           paths.OK: "negative", **{k: "unknown, excluded" for k in paths.UNKNOWN}}
    for k, v in sorted(d["error_type_counts"].items(), key=lambda kv: -kv[1]):
        L.append(f"| `{k}` | {v} | {cls[k]} |")
    L += ["", "`expert` marks items the annotator could not verify, so it is unknown and excluded from both classes. "
          f"Identity is question plus options. {d['duplicate_items']} items share an identical question and options with "
          "another item, all within the same fold.", "",
          "Writer `IRT-mislabeled-items` (ODC-BY) holds 1,001 flagged items only, not every benchmark item. Its "
          "multiple-choice weak positives are 12 for GSM-MC and 9 for MATH-MC, and GPQA is treated as all correct. No external "
          "benchmark reaches 100 weak positives, so H1b is not computable and no external benchmark is run. "
          "The item-level panel responses (`evaleval/EEE_datastore`) are not public under that name. A public copy holds "
          "GSM-MC and MATH-MC responses, which is moot given the label count.", "",
          "## Split", "",
          f"Base-rate-stratified subject split, sha256 `{o['split_sha256'][:16]}`. Counts exclude unknown items.", "",
          "| fold | subjects | known items | unknown | primary | any flaw | primary rate |", "|---|---:|---:|---:|---:|---:|---|"]
    for f in ("calibration_fit", "validation", "test"):
        x = F[f]
        L.append(f"| {f} | {x['subjects']} | {x['known']} | {x['unknown']} | {x['primary']} | {x['any_flaw']} | {_pct(x['primary_rate'])} |")
    t = F["test"]
    L += ["", f"Test has {t['primary']} primary positives, at least 100, so the 23 to 34 subject ratio stands.", "",
          "## Ceiling and power at each budget (test)", "",
          "| budget | rows flagged | random precision | best possible precision | Wilson half-width if precision is 30% |",
          "|---:|---:|---:|---:|---:|"]
    for b, x in t["budgets"].items():
        L.append(f"| {float(b):.2f} | {x['flagged']} | {100 * x['random_precision']:.1f}% | {100 * x['precision_ceiling']:.1f}% | "
                 f"{100 * x['wilson_halfwidth_at_p0.3']:.1f} points |")
    L += ["", "At a 3.5% base rate, precision at the 10% budget cannot exceed about a third even with a perfect ranking. "
          "It stays the preregistered primary metric, reported beside its ceiling and beside recall.", "",
          "## Panel", "",
          "7 models in 5 families. Local models fit in 6 GB: fp16 at 1.7B or less, NF4 above. OLMo-2-1B (AI2) is the reserve. "
          "Selection is confirmed on a 300-item calibration pilot: letter parse rate at least 95%, and accuracy above chance by "
          "its Wilson lower bound.", "",
          "| model | family | access | loading |", "|---|---|---|---|"]
    for p in o["panel"]:
        L.append(f"| `{p['model']}` | {p['family']} | {p['access']} | {p['loading']} |")
    L += ["", "Local models run on the original option order and one cyclic shift. API models run the original order only. "
          "All answers are direct letters with no reasoning, a deliberate low-cost regime.", "",
          "## Cost projection", "", f"Prices from `config/pricing.json`, priced on {c['priced_on']}. Estimates use rendered "
          "characters / 4 plus chat overhead until the pilot measures real token counts.", "",
          "| model | purpose | calls | input tokens per call | USD |", "|---|---|---:|---:|---:|"]
    for x in c["lines"]:
        L.append(f"| {x['model']} | {x['purpose']} | {x['n_calls']} | {x['input_tokens_per_call']} | {x['usd']:.3f} |")
    L += ["", f"Projected ${c['projected_usd']:.2f}. Spent so far ${c['total_usd']:.2f} (routing ${c['routing_usd']:.2f}). "
          f"Total after the pass ${c['after_usd']:.2f} of the ${c['cap_usd']:.0f} cap.", ""]
    return "\n".join(L)
