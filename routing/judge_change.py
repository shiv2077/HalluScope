"""Effect of replacing judge A (gpt-4o, the escalation model) with gpt-4.1-mini (ADR-033).

Compares the archived gpt-4o verdicts with the new judge A, and the old consensus with the new one, then lists every
cascade number before and after. Both sides are snapshots on the original 160-row calibration split, so later
calibration changes (ADR-035) do not mix in.
Writes results/judge_change.json and reports/routing_judge_change.md.
"""

from __future__ import annotations

import json

import pandas as pd

from . import data, stats
from .agreement import _kappa

OLD = data.RESULTS / "routing_judges_gpt-4o_gpt-4.1"
NEW = data.RESULTS / "routing_judges_gpt-4.1-mini_gpt-4.1_cal160"   # same 160-row calibration, new judge A only
OUT = data.RESULTS / "judge_change.json"
REPORT = data.REPORTS / "routing_judge_change.md"


def archived(split: str) -> pd.DataFrame:
    return pd.read_csv(data.DATA / "routing" / f"{split}_labels_judge_a_gpt-4o.csv", dtype=str, keep_default_na=False)


def _pair(a: pd.Series, b: pd.Series) -> dict:
    a, b = a.to_numpy(), b.to_numpy()
    return {"n": len(a), "agreement": stats.wilson(int((a == b).sum()), len(a)), "kappa": stats.boot(_kappa, a, b)}


def agreement(split: str) -> dict:
    lab = data.read_labels(split)
    lab = lab[lab["qid"].isin(set(archived(split)["qid"]))]   # only rows the old judge A saw (ADR-035 adds more)
    old_a = archived(split)[["qid", "model", "verdict"]].rename(columns={"verdict": "old_a"})
    new = lab.pivot_table(index=["qid", "model"], columns="judge", values="verdict", aggfunc="first").reset_index()
    m = new.merge(old_a, on=["qid", "model"])
    old_cons = data.consensus(pd.concat([lab[lab["judge"] == "judge_b"],
                                         archived(split).assign(judge="judge_a")], ignore_index=True))
    new_cons = data.consensus(lab)
    c = old_cons.merge(new_cons, on=["qid", "model"], suffixes=("_old", "_new"))
    flips = pd.crosstab(c["label_old"], c["label_new"]).stack().to_dict()
    return {"judge_a_old_vs_new": _pair(m["old_a"], m["judge_a"]),
            "judge_a_new_vs_judge_b": _pair(m["judge_a"], m["judge_b"]),
            "judge_a_old_vs_judge_b": _pair(m["old_a"], m["judge_b"]),
            "consensus_old_vs_new": _pair(c["label_old"], c["label_new"]),
            "consensus_transitions": {f"{a}->{b}": int(v) for (a, b), v in sorted(flips.items())}}


def _leaves(d, path=()):
    """Every dict with an 'est' under d, keyed by its path."""
    if isinstance(d, dict):
        if "est" in d:
            yield path, d
            return
        for k in sorted(d):
            yield from _leaves(d[k], (*path, str(k)))


def cascade_changes() -> list[dict]:
    old = json.loads((OLD / "evaluation.json").read_text())["cascade"]
    new = json.loads((NEW / "evaluation.json").read_text())["cascade"]
    nl = dict(_leaves(new))
    rows = []
    for path, o in _leaves(old):
        n = nl.get(path)
        if n is None or o["est"] is None or n["est"] is None:
            continue
        rows.append({"path": "/".join(path), "old": o, "new": n, "change": n["est"] - o["est"]})
    return rows


def _fmt(d: dict, pct: bool) -> str:
    f = (lambda x: f"{100 * x:.1f}%") if pct else (lambda x: f"{x:.3f}")
    return f"{f(d['est'])} [{f(d['lo'])}, {f(d['hi'])}]" if d.get("lo") is not None else f(d["est"])


def run() -> dict:
    out = {"judges_old": ["gpt-4o", "gpt-4.1"], "judges_new": ["gpt-4.1-mini", "gpt-4.1"],
           "agreement": {s: agreement(s) for s in data.SPLITS}, "cascade": cascade_changes()}
    old_cas = json.loads((OLD / "evaluation.json").read_text())["cascade"]
    new_cas = json.loads((NEW / "evaluation.json").read_text())["cascade"]
    out["rows_with_consensus"] = {"old": old_cas["_n"], "new": new_cas["_n"]}
    OUT.write_text(json.dumps(out, indent=1, sort_keys=True, default=float))
    L = ["# Routing: judge A without the escalation model", "",
         "Judge A was `gpt-4o`, which is also the strong model in the cascade, so the cascade numbers partly came from a model "
         "grading its own answers. Judge A is now `gpt-4.1-mini` (ADR-033). Judge B stays `gpt-4.1`. Both are still OpenAI "
         "models. Generated by `python3 -m routing.cli judge-change`.", "",
         f"Test rows with a consensus label: {out['rows_with_consensus']['old']} before, {out['rows_with_consensus']['new']} after.", "",
         "## Agreement", "", "| split | pair | n | agreement | kappa |", "|---|---|---:|---|---|"]
    for s, a in out["agreement"].items():
        for k in ("judge_a_old_vs_new", "judge_a_new_vs_judge_b", "judge_a_old_vs_judge_b", "consensus_old_vs_new"):
            v = a[k]
            L.append(f"| {s} | {k.replace('_', ' ')} | {v['n']} | {_fmt(v['agreement'], True)} | "
                     f"{_fmt(v['kappa'], False) if v['kappa'] else 'n/a'} |")
    L += ["", "Consensus transitions (old to new), test: " + ", ".join(f"{k} {v}" for k, v in out["agreement"]["test"]["consensus_transitions"].items()) + ".",
          "", "## Every cascade number, before and after", "", "| quantity | before | after | change |", "|---|---|---|---:|"]
    for r in out["cascade"]:
        pct = not any(x in r["path"] for x in ("cost_per_1000",))
        ch = f"{100 * r['change']:+.1f} points" if pct else f"{r['change']:+.3f}"
        L.append(f"| {r['path']} | {_fmt(r['old'], pct)} | {_fmt(r['new'], pct)} | {ch} |")
    REPORT.write_text("\n".join(L) + "\n")
    return out
