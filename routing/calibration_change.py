"""Risk lane before and after adding 700 calibration rows (ADR-035).

Before is the 160-row snapshot with the current judges and the 10% coverage start (ADR-033, ADR-034). After is the
current calibration. Writes results/calibration_change.json and reports/routing_calibration_change.md.
"""

from __future__ import annotations

import json

from . import data
from .judge_change import NEW as BEFORE

OUT = data.RESULTS / "calibration_change.json"
REPORT = data.REPORTS / "routing_calibration_change.md"


def _side(d: dict) -> dict:
    c = json.loads((d / "calibration.json").read_text())
    e = json.loads((d / "evaluation.json").read_text())["conformal"]
    return {"n": c["n"], "positives": c["positives"], "risk": c["risk"], "test": e}


def _cell(r: dict, t: dict) -> str:
    if r.get("threshold") is None:
        return "none qualifies"
    out = f"coverage {100 * r['coverage_cal']:.1f}%, risk {100 * r['risk_cal']:.1f}%, bound {r['ucb']:.3f}"
    cov, risk = t.get("coverage_test"), t.get("risk_test")
    if cov and risk:
        out += (f". Test: coverage {100 * cov['est']:.1f}% [{100 * cov['lo']:.1f}, {100 * cov['hi']:.1f}], "
                f"risk {100 * risk['est']:.1f}% [{100 * risk['lo']:.1f}, {100 * risk['hi']:.1f}]")
    return out


def run() -> dict:
    b, a = _side(BEFORE), _side(data.RESULTS)
    out = {"before": b, "after": a}
    OUT.write_text(json.dumps(out, indent=1, sort_keys=True, default=float))
    L = ["# Routing: the risk lane with more calibration rows", "",
         f"Calibration rows with a consensus label: {b['n']} before, {a['n']} after (ADR-035). Errors among them: "
         f"{b['positives']} before, {a['positives']} after. Learn-Then-Test with a Hoeffding bound at delta 0.1, fixed "
         "sequence from 10% coverage (ADR-034). Generated by `python3 -m routing.cli calibration-change`.", "",
         "| scorer | alpha | before | after |", "|---|---:|---|---|"]
    for sc in sorted(a["risk"]):
        for al in sorted(a["risk"][sc], key=float):
            L.append(f"| `{sc}` | {al} | {_cell(b['risk'][sc][al], b['test'].get(sc, {}).get(al, {}))} | "
                     f"{_cell(a['risk'][sc][al], a['test'].get(sc, {}).get(al, {}))} |")
    REPORT.write_text("\n".join(L) + "\n")
    return {"n_before": b["n"], "n_after": a["n"]}
